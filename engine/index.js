// EpisodeKit engine index — pure exports, no side effects.
// With no GLM_API_KEY the deterministic engine runs; output is identical in shape.

import { generateSuiteDeterministic } from "./lib.js";
import { generateSuiteGlm, hasGlm } from "./glm.js";

export { generateSuiteDeterministic, generateSuiteGlm, hasGlm };

export async function generateSuite(text) {
  return hasGlm() ? generateSuiteGlm(text) : generateSuiteDeterministic(text);
}

export function suiteToMarkdown(s) {
  const L = [];
  L.push(`# ${s.article.title}`, "");
  L.push(`> Themes: ${s.stats.themes.join(", ")} · ${s.stats.words} words · engine: ${s.engine}`, "");
  L.push("## Titles", ...s.titles.map((t, i) => `${i + 1}. ${t}`), "");
  L.push("## Summary", "", s.summary.text, "");
  L.push("## Article (show notes)", "");
  for (const sec of s.article.sections) {
    L.push(`### ${sec.heading}`, "");
    L.push(...sec.paragraphs.map((p) => p + "\n"));
  }
  const g = s.discussion;
  L.push(`## ${g.title}`, "", `**Opener.** ${g.opener}`, "", "**Opening questions**", ...g.open.map((q, i) => `${i + 1}. ${q}`), "");
  L.push("**From the episode**");
  for (const q of g.qs) L.push(`> “${q.quote}”`, "", `- ${q.follow}`, "");
  L.push("**Apply it**", ...g.apply.map((q, i) => `${i + 1}. ${q}`), "", `**Closing.** ${g.closing}`, "");
  L.push("## Email series (5 days)", "");
  for (const d of s.series) {
    L.push(`### ${d.title}`, "", `**Re-listen:** “${d.anchor}”`, "", d.reflection, "", `**Do this:** ${d.action}`, "", `**Sign-off:** ${d.closing}`, "");
  }
  L.push("## Social pack", "");
  L.push("**Pull quotes**", ...s.social.pullQuotes.map((q) => `> “${q}”`), "");
  L.push("**Captions**", ...s.social.captions.map((c) => `- ${c.text.replace(/\n/g, " / ")}`), "");
  L.push("**X posts**", ...s.social.xPosts.map((c) => `- ${c.text.replace(/\n/g, " / ")}`), "");
  return L.join("\n");
}

